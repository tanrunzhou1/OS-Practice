========================================
预期输出：（成功删除，无错误输出）

dir
========================================
预期输出：test.txt 已消失，显示 test_copy.txt, test2.txt, testdir, dir1, dir2

rmdir /testdir
========================================
预期输出：（成功删除目录）

dir
========================================
预期输出：testdir 已消失

rmdir /dir1
========================================
