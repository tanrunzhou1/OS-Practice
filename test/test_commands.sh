文件系统完整测试用例
========================================

--- 第1组：帮助和基本信息 ---
help
========================================
预期输出：显示所有可用命令列表

sum
========================================
预期输出：显示磁盘空间信息（Total Blocks, Used Blocks, Free Blocks, Total Inodes, Used Inodes, Free Inodes）

dir
========================================
预期输出：显示当前目录内容（空目录显示 "(empty directory)"）


--- 第2组：目录操作 ---
mkdir /testdir
========================================
预期输出：Directory created: /testdir

dir
========================================
预期输出：显示 testdir 目录

mkdir /dir1
========================================
预期输出：Directory created: /dir1

mkdir /dir2
========================================
预期输出：Directory created: /dir2

dir
========================================
预期输出：显示 testdir, dir1, dir2

cd /dir1
========================================
预期输出：Changed directory to: /dir1
提示符变为：/dir1 $

pwd (如果支持)
========================================
预期输出：/dir1

cd /
========================================
预期输出：Changed directory to: /
提示符变为：/ $


