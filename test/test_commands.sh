--- 第5组：复制文件 ---
cp /test.txt /test_copy.txt
========================================
预期输出：（成功复制，无错误输出）

dir
========================================
预期输出：显示 test.txt, test_copy.txt, test2.txt, testdir, dir1, dir2

cat /test_copy.txt
========================================
预期输出：显示与 test.txt 相同的内容


--- 第6组：删除操作 ---
